"""Распознавание слоя по образцу имени, когда точного совпадения нет.

`MOSGEOTREST_LAYER_MAP` сопоставляет имена дословно, и на геоподоснове это
работает: листы Мосгеотреста выгружаются одним экспортёром и называют слои
одинаково. На проектных чертежах — нет. В пилотном датасете каждое бюро вело
свой стандарт, и одно и то же понятие встречается под именами вроде
`!Посадка_Дерево`, `ГП_ПБ_Озеленение_Посадка_Деревья`,
`оникс_ГП_посадки_Деревья`, `ПРОЕКТИРУЕМЫЕ ДЕРЕВЬЯ`,
`!!!_Высаживаемые деревья_кусты_ПБл` — восемь конвенций на девятнадцать улиц.
Дословная карта покрывала семь улиц из девятнадцати.

Правила применяются ПОСЛЕ точной карты, а не вместо неё. Точная карта —
проверенная и однозначная; правило по подстроке неизбежно приблизительно, и
там, где имя известно дословно, гадать незачем.

Порядок правил значим: первое совпавшее выигрывает, поэтому частные образцы
идут раньше общих. Отдельно отсекаются служебные слои (выноски, номера,
экспликации, штампы): в их названиях те же слова, что и в содержательных,
и без явного исключения «Дендра_выноски_сохранить» стала бы существующей
зеленью, а «_ПП_газон_экспликация» — газоном.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Literal

Kind = Literal["utility", "zone"]


def normalize_name(name: str) -> str:
    """Регистр, «ё» и разделители не должны решать.

    В именах слоёв разделителем бывает что угодно — `_`, `$`, `-`, пробел,
    точка — и одно и то же понятие пишется то `Посадка_Дерево`, то
    `посадки Деревья`. Приведение к пробелам делает образцы читаемыми и
    избавляет от перечисления разделителей в каждом регулярном выражении.
    """
    lowered = name.lower().replace("ё", "е")
    return " ".join(re.split(r"[\s_\-$/\\.,()\[\]|]+", lowered)).strip()


# Служебные слои: оформление, а не объекты. Совпадение здесь отменяет любое
# другое — эти слова встречаются внутри содержательных имён.
ANNOTATION_PATTERNS = (
    r"выноск",
    r"номер",
    r"подпис",
    r"экспликац",
    r"ведомост",
    r"штамп",
    r"рамк",
    r"легенд",
    r"условн\w* обознач",
    r"\bтекст\b",
    r"\bразмер\w*\b",
    r"привязк",
    r"комментар",
    # Проектные чертежи здесь наполовину на английском (`!Project_road
    # dimension 500`, `!Project_title`), и служебные слои у них называются
    # английскими словами — без них выноски и размеры уезжали бы в объекты.
    r"\bdimension",
    r"\bannotation",
    r"\blabel",
    r"\bcallout",
    r"\btitle\b",
    r"\blegend",
    r"\bstamp\b",
)

_ANNOTATION = re.compile("|".join(ANNOTATION_PATTERNS))


@dataclass(frozen=True)
class LayerRule:
    """Один образец имени -> тип объекта."""

    pattern: str
    kind: Kind
    object_type: str
    note: str = ""

    def matches(self, normalized: str) -> bool:
        return re.search(self.pattern, normalized) is not None


# Порядок значим: частное раньше общего.
LAYER_RULES: tuple[LayerRule, ...] = (
    # --- инженерные сети ---
    LayerRule(r"газопровод|газоснабж", "utility", "gas_pipe"),
    LayerRule(r"теплосет|теплотрасс|теплопровод|тепловая сет|\bтс\b", "utility", "heat_network"),
    LayerRule(r"водопровод|водоснабж", "utility", "water_pipe"),
    LayerRule(r"канализац|водосток|ливнев|дренаж|коллектор", "utility", "sewer"),
    LayerRule(r"кабел|\bкл\b|слаботочк|связи|мгтс", "utility", "cable_line"),
    # `контакт?н` (не только `контактн`) — живая находка, 4. Харьковская
    # улица: тот же слой «Опоры контактной сети» встречается и с опечаткой
    # апстрима «Опоры контакНОЙ сети» (без «т» — см. MOSGEOTREST_LAYER_MAP's
    # комментарий про эту же опечатку в другом слое). Без этого расширения
    # опечатанное написание не совпадало ни с одним правилом и уходило в
    # unknown, а исправленное — уже размечалось сюда же.
    LayerRule(r"\bлэп\b|воздушн\w* лини|\bвл \d|контакт?н\w* сет", "utility", "power_line_corridor"),
    # --- препятствия и контекст ---
    # Школа/детсад раньше общего «здания»: у них вдвое больший отступ
    # (743-ПП, табл. 3.6.1), и попади они в общее правило — норма потерялась бы.
    LayerRule(r"школ|детск\w* сад|\bдоу\b|дошкольн", "zone", "school_kindergarten"),
    LayerRule(r"подпорн\w* стен", "zone", "retaining_wall"),
    LayerRule(r"трамва", "zone", "tram_track"),
    LayerRule(r"\bоткос|террас", "zone", "slope_toe"),
    # Светофор — та же строка таблицы, что и опора освещения: «мачта и опора
    # осветительной сети, трамвая, мостовая опора и эстакада» (СП 42.13330.2016
    # табл. 9.1, 743-ПП табл. 3.6.1). Светофор стоит на такой же опоре.
    LayerRule(r"фонар|опор\w* освещ|торшер|светильник|\bстолб|светофор|мачт", "zone", "lighting_pole"),
    LayerRule(r"тротуар|садов\w* дорожк|пешеходн\w* дорожк", "zone", "sidewalk"),
    # Фонтан и памятник читаются как «сооружение» из строки «Наружная стена
    # здания и сооружения» — это суждение, а не буква акта: отдельной строки
    # под них в таблицах нет, но по существу это капитальный объект, от
    # которого отступ такой же. Ограды, береговая линия и красные линии
    # намеренно НЕ сопоставлены: ни один из доступных актов не задаёт до них
    # расстояние, и придумать его означало бы выдать догадку за норму.
    LayerRule(r"здани|строени|сооружени|крыльц|навес|павильон|фонтан|памятник|монумент", "zone", "building"),
    # `\bбр\b.*\d+.*\d+|\bгп[123]\b` -- живая находка на «1. Олимпийская
    # деревня»: там борт называется ЕЩЁ короче -- голым кодом изделия без
    # слова «борт» вообще («БР 1000 300 150», «ГП1 (300x150)», сверено с
    # легендой чертежа: «Борт БР 1000x300x150», «Борт ГП1»). «БР» само по
    # себе слишком общий токен -- ограничен требованием минимум двух чисел
    # рядом (это код-размер, не что-то ещё). «ГП1/ГП2/ГП3» с цифрой сразу
    # после -- достаточно узко, «ГП» само по себе в этом файле означает
    # «Генплан» и используется в десятках других слоёв, но «ГП» + цифра
    # 1-3 рядом -- только этот код бордюра.
    LayerRule(r"\bбр\b.*\d+.*\d+|\bгп[123]\b", "zone", "road"),
    # `\bборт\w*` (не только полная фраза «бортовой камень») — живая находка на
    # 4. Харьковской улице: у этого бюро борт называется через код изделия
    # (`ДВ_ГП_П_Борт_БР100.30.15`, `..._Борт_Пониженный`, `..._Борт_ГП1`,
    # `..._Борт_ГП2-ГП3`), и полная фраза его не ловила — все четыре уходили в
    # unknown, хотя физическая роль та же, что у уже сопоставленного
    # «Бортовой камень». Частный образец `бортов\w* камен` избыточен на фоне
    # этого (борт\w* — его надмножество), но оставлен для читаемости истории.
    # `\bkerb\b` — живая находка на «2. Песчаный переулок»: третья манера
    # называть тот же борт, на этот раз английским словом в смешанном
    # русско-английском шаблоне слоя («!Project_road kerb - БР100.30.15
    # внутренний/внешний», «...- ГП1 внешний») — ни «борт», ни существующий
    # `\bбр\b.*\d+.*\d+` не совпадают: код здесь приклеен к «БР» без пробела
    # («БР100.30.15»), из-за чего `\bбр\b` не находит границу слова сразу
    # после «р». Стоило 197 радиусных ARC-сегментов борта (дуги на
    # повороте/перекрёстке, отдельными сущностями — не бульж внутри
    # полилинии) + 28 изогнутых LWPOLYLINE («... БР100.30.15 пониж»),
    # ушедших в unknown вместо road.
    LayerRule(r"бортов\w* камен|\bборт\w*|бордюр|проезжа\w* част|дорожн\w* покрыт|\bпроезд\b|\bkerb\b", "zone", "road"),
    # Реальная заливка поверхностей (не оформление — HATCH-геометрия с
    # площадью, см. dxf_reader._hatch_to_geometry). Бюро называет слои парой
    # кодов через дефис ("_ГЗН-АБ ПЧ" — шов между газоном и асфальтом проезжей
    # части), normalize_name разбивает дефис на пробел, поэтому коды здесь —
    # отдельные слова. Порядок — снова частное раньше общего: одиночный «гзн»
    # опознаётся раньше двусоставных кодов асфальта, а те написаны в обоих
    # порядках («аб ... пч» и «пч ... аб»), потому что реальное имя слоя
    # называет то одну, то другую сторону шва первой. Голый «щ» (щебень) и
    # «змс» намеренно не сопоставлены — соответствие неочевидно, а площадь
    # этих слоёв в замерах пренебрежимо мала (см. CLAUDE.md).
    #
    # Отдельный zone_type от `existing_greenery`, не тот же: это заливка типа
    # поверхности («здесь сейчас газон», ровно как «здесь асфальт») из
    # чертежа Заливки, а не съёмка существующих насаждений. Существующий
    # газон — не препятствие для новой посадки (дерево или куст можно
    # поставить прямо в газон, это норма, см. параграф «Дерево/куст поверх
    # газона» в CLAUDE.md), в отличие от настоящего дерева/куста/полосы
    # деревьев. Смешивать их в одну твёрдую категорию было бы неточностью,
    # даже если на проверенных пилотных улицах она не меняла результат (см.
    # находку про existing_greenery/газон в CLAUDE.md).
    LayerRule(r"\bгзн\b", "zone", "existing_lawn"),
    LayerRule(r"\b(аб|щма)\b.*\bпч\b|\bпч\b.*\b(аб|щма)\b", "zone", "road"),
    LayerRule(r"\b(аб|пл)\b.*\bтр\b|\bтр\b.*\b(аб|пл)\b", "zone", "sidewalk"),
    # "ДВ_ПП_ДО_ТипN_..." -- a different, unrelated naming convention (found
    # on 4. Харьковская улица) for pavement repair/construction scope, not
    # the Заливки.dwg HATCH codes above ("ДО" reads as "дорожная одежда" --
    # road pavement structure -- and "ТипN" as a standard pavement-type
    # code). Confirmed live, not assumed: every one of these polygons (107
    # objects, 23 046 m2 total, real Polygon geometry already -- no
    # reconstruction needed) sits within 3 m of an already-mapped road curb
    # line, so this genuinely traces carriageway/sidewalk surface, not
    # something that coincidentally contains "пч"/"трот". Bare tokens, same
    # trust level the "аб"/"пч"/"тр" HATCH codes above already get.
    # "...Устройство_уширений_местные" doesn't name "пч" itself, but the
    # user found and read the drawing's own legend (АПОТ Харьковская, лист
    # условных обозначений): "Устройство уширений (замена КДО) на местных
    # улицах и проездах по типу 4" -- уширение проезжей части на местных
    # улицах, не тротуара, confirmed from the source, not guessed.
    # "...Устройство_площадки" (no type number, 9 objects) is still left
    # unmapped -- that legend has no area-fill entry for a bare "площадка"
    # at all (only a point symbol for "Проектируемая площадка ТБО", a small
    # waste-collection pad -- a different, much smaller kind of object than
    # a 2273 m2/9-object polygon layer), so there's nothing to confirm
    # either the surface or even that it's the same kind of thing.
    # Bare "щма" (without a paired "пч", unlike the Заливки.dwg rule above) --
    # live find, «1. Олимпийская деревня»'s own layer list («Тип 1 (рем.
    # щма)», a pavement-repair-type series sibling to Харьковская's
    # "ДВ_ПП_ДО_ТипN"). ЩМА (щебёночно-мастичный асфальт) is asphalt-only
    # material in every layer name seen in this dataset -- never used for a
    # sidewalk course -- so a bare mention is safe to read as road on its own.
    LayerRule(r"\bпч\b|уширени|\bщма\b", "zone", "road"),
    LayerRule(r"\bтрот\b", "zone", "sidewalk"),
    # --- граница участка ---
    LayerRule(r"границ\w* работ|границ\w* проектирован|границ\w* благоустройств", "zone", "territory"),
    # --- существующее озеленение ---
    # Обязательно ПОСЛЕ проектных посадок не идёт: проектные посадки вообще не
    # являются ограничением и распознаются отдельной функцией ниже. Здесь —
    # только то, что уже растёт и что buildable_area вычитает как препятствие.
    #
    # «леса и газон» здесь — намеренно ОСТАЁТСЯ existing_greenery (твёрдым
    # препятствием), а не existing_lawn, хотя название слоя буквально
    # признаётся смешанным («леса И газоны»). Разница с правилом «гзн» выше —
    # это не тот же самый слой под другим именем: «гзн» — код заливки типа
    # поверхности с чертежа Заливки (однозначно про сам факт «здесь газон»),
    # а этот слой — топографическая съёмка существующей растительности, где
    # реальный лес/полоса деревьев вполне может лежать под тем же именем.
    # Развести дерево от газона внутри ОДНОГО такого слоя нечем — в данных
    # для этого нет отдельного признака, — и подставлять сюда предположение
    # означало бы выдать догадку за факт. Более консервативный (твёрдое
    # препятствие) вариант — безопасная сторона ошибки: неверно исключить
    # клочок газона дешевле, чем неверно разрешить посадку внутрь настоящего
    # дерева.
    #
    # «границ\w* растительности» (буквально «Граница растительности и
    # грунта») — живая находка на «4. Харьковская улица»: слой
    # шёл в `unknown` (11 388 объектов — крупнейший неопознанный слой на
    # улице), пользователь принял его за «исходный газон, который не
    # видно». Проверено не по названию, а по факту: конвертированы и
    # проверены оба типа исходников этой улицы — слой присутствует ВО ВСЕХ
    # трёх топопланах («tp», геобаза/топосъёмка) и ОТСУТСТВУЕТ в дендроплане
    # и в главном чертеже (АПОТ) — то есть это подлинная топографическая
    # съёмка существующего покрова, а не элемент чьего-то проекта. Тот же
    # принцип, что и у «леса и газон» чуть выше: граница «растительность/
    # грунт» не разводит дерево от газона внутри себя, поэтому
    # existing_greenery (твёрдое препятствие), не existing_lawn.
    LayerRule(
        r"леса и газон|полоса деревьев|отдельно стояще\w* дерев|существующ\w* (растени|дерев|куст|зелен)"
        r"|границ\w* растительности",
        "zone",
        "existing_greenery",
    ),
)

# Слои, у которых точка вставки символа и есть объект: разворачивать блок
# нельзя, иначе одно дерево превращается в кружки и чёрточки значка.
SYMBOL_PATTERNS = (
    r"отдельно стояще\w* дерев",
    r"колодц",
    r"\bлюк",
    r"фонар",
    r"\bстолб",
    r"геодезическ\w* пункт",
)

_SYMBOL = re.compile("|".join(SYMBOL_PATTERNS))


def is_annotation_layer(name: str) -> bool:
    """Слой оформления, а не объектов."""
    return _ANNOTATION.search(normalize_name(name)) is not None


def is_symbol_layer(name: str) -> bool:
    """Слой значков: точка вставки и есть объект."""
    return _SYMBOL.search(normalize_name(name)) is not None


def classify_layer(name: str) -> tuple[Kind, str] | None:
    """(kind, object_type) для слоя, распознанного по образцу имени.

    None — если имя служебное или ни на что не похоже. Именно None, а не
    «unknown»: вызывающий обязан различать «распознали как неизвестный тип» и
    «не распознали вовсе», иначе служебные слои попадут в проект как зоны.
    """
    normalized = normalize_name(name)
    if not normalized or _ANNOTATION.search(normalized):
        return None
    for rule in LAYER_RULES:
        if rule.matches(normalized):
            return rule.kind, rule.object_type
    return None


